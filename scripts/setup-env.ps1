SUPABASE_SERVICE_ROLE_KEY=$($map['SUPABASE_SERVICE_ROLE_KEY'])

# Single-user auth: one shared password + signed session cookie.
APP_PASSWORD=$($map['APP_PASSWORD'])
SESSION_SECRET=$($map['SESSION_SECRET'])
OWNER_USER_ID=00000000-0000-0000-0000-000000000001
