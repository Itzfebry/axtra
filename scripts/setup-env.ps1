# Derive backend/.env and frontend/.env.local from the root .env (secrets not printed).
# Generates APP_PASSWORD and SESSION_SECRET once and persists them to the root .env.
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$rootEnvPath = Join-Path $root '.env'
$raw = [IO.File]::ReadAllText($rootEnvPath)
$map = @{}
foreach ($line in ($raw -split "`n")) {
    $t = $line.Trim()
    if ($t -and -not $t.StartsWith('#')) {
        $i = $t.IndexOf('=')
        if ($i -gt 0) { $map[$t.Substring(0, $i).Trim()] = $t.Substring($i + 1).Trim() }
    }
}

function New-Secret([int]$bytes) {
    $buffer = New-Object 'byte[]' $bytes
    [Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($buffer)
    return [Convert]::ToBase64String($buffer)
}

$added = @()
if (-not $map['APP_PASSWORD']) {
    $map['APP_PASSWORD'] = New-Secret 12
    $added += "APP_PASSWORD=$($map['APP_PASSWORD'])"
}
if (-not $map['SESSION_SECRET']) {
    $map['SESSION_SECRET'] = New-Secret 32
    $added += "SESSION_SECRET=$($map['SESSION_SECRET'])"
}
if ($added.Count -gt 0) {
    $suffix = "`n# Single-user auth (generated by scripts/setup-env.ps1)`n" + ($added -join "`n") + "`n"
    [IO.File]::AppendAllText($rootEnvPath, $suffix)
    "generated auth secrets and appended them to root .env"
}
"parsed: " + $map.Count + " vars"

$backend = @"
